#!/usr/bin/env python3
"""r16 course preservation: accepted r15 course tapes replayed through the r16 main.

each route of checkpoints/spillway/r15/release-plan/ROUTES.json is a fixed, open-loop input tape
(key and relative-mouse events applied by the tape executor) with the trace the accepted r15 main
produced. this plays the same tape on res://scripts/r16_main.gd (only the start map and the
replay sensitivity are set, as tools/package-r15.py does for r15) and compares every tick with the
r15 reference: feet exactly, velocity exactly, yaw, and the course clock, checkpoint, finish and
respawns. `--recordings` plays it a second way with recording on into an isolated folder, then
reads the attempt files back with tools/analyze-r16-runs.py and checks the recorded feet, velocity,
view and clock against the same trace, tick for tick.

it runs on an imported copy of the project, never the shared checkout:
python3 -I tests/test_r16_loop_tapes.py --project SRC --out DIR [--routes a,b] [--recordings] [--all]
"""
import argparse
import gzip
import importlib.util
import json
import os
from pathlib import Path
import struct
import subprocess
import sys
import time

OUTER = Path(__file__).resolve().parents[4]
ROUTES = OUTER / 'checkpoints/spillway/r15/release-plan/ROUTES.json'
DEFAULT_ROUTES = ['breakwater-basic', 'whiteout-crouch', 'night-f5-earned']
# the movement lab plays the r16 lab runner, whose wall jump is limited on purpose
# (docs/r16/LAB.md): the r15 lab tape's third air Space press (tick 1290, after two kicks)
# is refused, so the line differs from tick 1291 on. retained as a known law difference; the
# control plays the same tape on the r16 host with the frozen r15 lab runner and must be exact.
LAB_LAW_DIFFERENCE = {'lab-combined': 1291}
R15_LAB_RUNNER = 'res://scripts/r15_experiment_player.gd'


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def engine_env(root):
    env = {'PATH': os.environ.get('PATH', '/usr/bin:/bin'), 'HOME': str(Path.home()), 'LANG': 'C.UTF-8'}
    for name in ['XDG_DATA_HOME', 'XDG_CONFIG_HOME', 'XDG_CACHE_HOME', 'XDG_STATE_HOME', 'XDG_RUNTIME_DIR']:
        path = root / name.split('_')[1].lower()
        path.mkdir(parents=True, exist_ok=True, mode=0o700)
        env[name] = str(path)
    if os.environ.get('GODOT'):
        env['GODOT'] = os.environ['GODOT']
    return env


def route_game(route, path, runs=None, runner=None):
    lines = ['extends "res://scripts/r16_main.gd"',
             '## generated by tests/test_r16_loop_tapes.py for route %s: normal spawn of the named map, records off.' % route['name'],
             '## no gameplay method, progress, input or movement is overridden.',
             'func _init() -> void:',
             '\tmap_id = %s' % json.dumps(route['map'])]
    if 'sensitivity' in route:
        lines.append('\tsource_sensitivity_override = %r' % route['sensitivity'])
    if runner is not None:
        lines.append('\tsource_runner = %s  # labelled control: the frozen r15 lab runner' % json.dumps(runner))
    if runs is not None:
        lines.append('\trecordings_dir = %s' % json.dumps(str(runs)))
        lines.append('\trecord_runs = true')
    path.write_text('\n'.join(lines) + '\n')
    return path


def play(route, project, out, runs, package, runner=None, law_from=None):
    out.mkdir(parents=True, exist_ok=True)
    env = engine_env(out / 'profile')
    tool = project / 'tools/momentum-tape.py'
    expanded = out / 'tape.expanded.json'
    done = subprocess.run([sys.executable, '-I', str(tool), 'expand', route['tape']], cwd=project, env=env, capture_output=True, text=True, timeout=120)
    if done.returncode:
        return {'ok': False, 'error': 'expand failed: ' + done.stderr[-400:]}
    expanded.write_text(done.stdout)
    plan = json.loads(done.stdout)
    hz = int(plan['physics_hz'])
    game = route_game(route, out / 'route-game.gd', runs, runner)
    run = out / 'run'
    started = time.time()
    done = subprocess.run([sys.executable, '-I', str(tool), 'run', str(expanded), '--out', str(run), '--headless', '--render-fps', str(route.get('fps', hz)),
                           '--warmup', str(route.get('warmup', 8)), '--wall-budget', '500', '--game-script', str(game), '--game-class', '', '--motor', route['preset']],
                          cwd=project, env=env, capture_output=True, text=True, timeout=700)
    (out / 'run.log').write_text(done.stdout + '\n' + done.stderr)
    trace = run / 'evaluator/trace.jsonl'
    rows = package.read_rows(trace) if trace.is_file() else []
    report = json.loads((run / 'evaluator/report.json').read_text()) if (run / 'evaluator/report.json').is_file() else {}
    result = {'route': route['name'], 'exit': done.returncode, 'ticks': len(rows), 'expected_ticks': int(plan['duration_ticks']), 'seconds': round(time.time() - started, 1),
              'end': report.get('end'), 'neutral': report.get('neutral'), 'integrity_flags': report.get('integrity_flags'),
              'rate_ok': (report.get('rate') or {}).get('ok'), 'delivery_ok': (report.get('delivery') or {}).get('ok'), 'order_ok': (report.get('order') or {}).get('ok')}
    invalid = package.trace_error(rows, expected=int(plan['duration_ticks']))
    result['invalid'] = invalid
    reference = package.read_rows(route['reference'])
    result['compare'] = package.compare_traces(rows, reference, route.get('game_diff', []))
    last = rows[-1]['game'] if rows else {}
    result['finish'] = last
    engine_log = run / 'evaluator/godot.log'
    text = engine_log.read_text(errors='replace') if engine_log.is_file() else ''
    result['engine_errors'] = [line for line in text.splitlines() if 'ERROR' in line or 'SCRIPT ERROR' in line][:10]
    if law_from is None:
        same = bool(result['compare'].get('ok')) and last.get('finish_kind') == 'clean' and not last.get('respawns')
    else:
        # identical up to the known law difference, then free to differ.
        first = result['compare'].get('first_position_difference_tick')
        game_ticks = result['compare'].get('game_difference_ticks') or []
        same = first is not None and first >= law_from and all(t >= law_from for t in game_ticks)
        result['law_difference'] = {'expected_from_tick': law_from, 'first_position_difference_tick': first, 'first_game_difference_tick': game_ticks[0] if game_ticks else None}
    result['ok'] = (done.returncode == 0 and not invalid and same and result['rate_ok'] is True and result['delivery_ok'] is True and result['order_ok'] is True
                    and report.get('end') == 'completed' and not result['engine_errors'])
    if runs is not None:
        result['recordings'] = check_recordings(runs, rows, project, expect_finish=law_from is None)
        result['ok'] = result['ok'] and result['recordings']['ok']
    # the evaluator's raw trace is large; the comparison above is what is kept.
    for big in [trace, run / 'evaluator/trace.jsonl.gz']:
        if big.is_file():
            big.unlink()
    return result


def check_recordings(runs, rows, project, expect_finish=True):
    """the finish attempt's recording (or, on a line that does not finish, the attempt sealed when
    the executor quit) against the executor's post-step trace, tick for tick."""
    analyzer = load_module(project / 'tools/analyze-r16-runs.py', 'analyze_r16_runs')
    files = sorted(runs.glob('*.r16run*'))
    out = {'files': [f.name for f in files], 'ok': False}
    finishes = []
    for path in files:
        rec = analyzer.read(path)
        outcome = (rec.seal or {}).get('outcome', {})
        if rec.ok and outcome.get('kind') == ('finish' if expect_finish else 'quit'):
            finishes.append(rec)
    out['finish_files'] = len(finishes)
    if len(finishes) != 1:
        out['error'] = 'expected exactly one sealed finish recording'
        return out
    rec = finishes[0]
    c = rec.columns
    n = len(c['tick'])
    recorded = [(c['p_x'][i], c['p_y'][i], c['p_z'][i]) for i in range(n)]
    trace = [tuple(f32(x) for x in r['post']['p']) for r in rows]
    # recording tick 0 is the first frame after the spawn; the tape starts after its warmup.
    offset = next((o for o in range(n) if recorded[o] == trace[0] and recorded[o:o + 8] == trace[:8]), None)
    out.update({'ticks': n, 'offset': offset, 'outcome': rec.seal.get('outcome'), 'identity': rec.header.get('identity'),
                'metadata_keys': sorted(rec.header.get('metadata', {}).keys())})
    if offset is None:
        out['error'] = 'no alignment between the recording and the trace'
        return out
    worst = {'p': 0.0, 'v': 0.0, 'yaw': 0.0, 'elapsed': 0.0}
    first_bad = None
    compared = 0
    for t, row in enumerate(rows):
        i = offset + t
        if i >= n:
            break
        compared += 1
        post, game = row['post'], row['game']
        diffs = {'p': max(abs(f32(a) - b) for a, b in zip(post['p'], recorded[i])),
                 'v': max(abs(f32(a) - b) for a, b in zip(post['v'], (c['v_x'][i], c['v_y'][i], c['v_z'][i]))),
                 'yaw': abs(post['yaw'] - c['yaw'][i]), 'elapsed': abs(game['elapsed'] - c['elapsed'][i])}
        for k in worst:
            worst[k] = max(worst[k], diffs[k])
        if first_bad is None and any(v > 0 for v in diffs.values()):
            first_bad = {'tick': t, 'diffs': diffs}
    finish_row = next((t for t, r in enumerate(rows) if r['game'].get('finished')), None)
    out.update({'compared': compared, 'worst': worst, 'first_difference': first_bad, 'trace_finish_tick': finish_row,
                'recording_last_trace_tick': n - 1 - offset})
    seal = rec.seal
    out['seal'] = {k: seal.get(k) for k in ('timer_start_tick', 'finish_tick', 'last_tick')}
    out['inputs'] = input_alignment(rec, rows, offset)
    if not expect_finish:
        # quit after the last tape tick: every tape tick is in the file, the seal is a quit.
        out['ok'] = first_bad is None and compared == len(rows) and out['inputs']['ok'] and seal.get('outcome', {}).get('kind') == 'quit'
        return out
    out['style'] = style_sealing(rec)
    out['ok'] = (first_bad is None and compared == n - offset and finish_row == n - 1 - offset and seal.get('outcome', {}).get('clean') is True
                 and out['inputs']['ok'] and out['style']['ok'] and seal.get('finish_tick') == n - 1 and seal.get('last_tick') == n - 1)
    return out


KEYCODES = {'w': 87, 'a': 65, 's': 83, 'd': 68, 'space': 32, 'c': 67, 'e': 69, 'f': 70, 'r': 82, 'ctrl': 4194326, 'shift': 4194325, 'escape': 4194305}


def input_alignment(rec, rows, offset):
    """the executor applies each key edge before the tick it is listed under (late in the frame
    before, or at the process arm) and each mouse delta early in that tick's frame. the session
    samples at priority 999, before the executor's late node, so every edge must be recorded on
    the recording tick that matches its trace tick, never one earlier."""
    i = rec.inputs
    keys_at, mouse_at = {}, {}
    for k in range(len(i['tick'])):
        if i['kind'][k] == 1:
            keys_at.setdefault(i['tick'][k], []).append((i['aux'][k] or i['code'][k], bool(i['flags'][k] & 1)))
        elif i['kind'][k] == 3:
            mouse_at.setdefault(i['tick'][k], []).append((i['x'][k], i['y'][k]))
    last = len(rec.columns['tick']) - 1
    expected_keys = expected_mouse = 0
    misplaced = []
    for t, row in enumerate(rows):
        at = offset + t
        if at > last:
            break
        want = sorted((KEYCODES.get(k['key'], -1), k['edge'] == 'press') for k in row.get('keys', []))
        got = sorted(keys_at.get(at, []))
        expected_keys += len(want)
        if want != got:
            misplaced.append({'trace_tick': t, 'recording_tick': at, 'want': want, 'got': got, 'before': sorted(keys_at.get(at - 1, []))})
        mouse = row.get('mouse')
        want_m = [(f32(mouse['screen_relative'][0]), f32(mouse['screen_relative'][1]))] if mouse else []
        expected_mouse += len(want_m)
        if want_m != mouse_at.get(at, []):
            misplaced.append({'trace_tick': t, 'recording_tick': at, 'want_mouse': want_m, 'got_mouse': mouse_at.get(at, [])})
    # nothing may sit on the recording's idle ticks before the tape began.
    early = sorted(t for t in set(keys_at) | set(mouse_at) if t < offset)
    return {'ok': not misplaced and not early and expected_keys > 0, 'key_edges': expected_keys, 'mouse_rows': expected_mouse,
            'misplaced': misplaced[:5], 'misplaced_count': len(misplaced), 'inputs_before_tape': early[:5]}


def style_sealing(rec):
    """the seal's style total includes its first finish sample and never later samples."""
    styled = [e for e in rec.events if e.get('s') == 'capture']
    total = sum(int((e.get('d') or {}).get('points', 0)) for e in styled)
    outcome = (rec.seal or {}).get('outcome', {})
    finish = rec.seal.get('finish_tick')
    late = [e for e in styled if finish is not None and e.get('t', -1) > finish]
    score = (outcome.get('style') or {}).get('score')
    return {'ok': score == total and not late and (outcome.get('style') or {}).get('best_eligible') is True, 'score': score, 'event_sum': total,
            'events': len(styled), 'events_after_finish': len(late)}


def main(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument('--project', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--routes', default=','.join(DEFAULT_ROUTES))
    parser.add_argument('--all', action='store_true')
    parser.add_argument('--recordings', action='store_true', help='also play each route with recording on and check the files')
    parser.add_argument('--routes-file', type=Path, default=ROUTES, help='the accepted R15 ROUTES.json (default: beside this checkout)')
    args = parser.parse_args(argv)
    project = args.project.resolve()
    package = load_module(project / 'tools/package-r15.py', 'package_r15')
    routes = json.loads(args.routes_file.read_text())
    wanted = [r['name'] for r in routes] if args.all else args.routes.split(',')
    results = []
    for name in wanted:
        route = next((r for r in routes if r['name'] == name), None)
        if route is None:
            results.append({'route': name, 'ok': False, 'error': 'not in ROUTES.json'})
            continue
        spec = dict(field.split('=', 1) for field in route['spec'].split(','))
        merged = {'name': name, 'map': spec['map'], 'preset': spec['preset'], 'tape': spec['tape'], 'reference': route['reference'], 'warmup': int(spec.get('warmup', 8))}
        if 'sensitivity' in spec:
            merged['sensitivity'] = float(spec['sensitivity'])
        law_from = LAB_LAW_DIFFERENCE.get(name)
        variants = [('plain', None, None)] + ([('recorded', args.out / name / 'recorded' / 'runs', None)] if args.recordings else [])
        if law_from is not None:
            variants.append(('r15-lab-runner', None, R15_LAB_RUNNER))
        for label, runs, runner in variants:
            result = play(merged, project, args.out / name / label, runs, package, runner, law_from if runner is None else None)
            result['variant'] = label
            results.append(result)
            print('%s %-20s %-14s ticks=%s pos=%s vel=%s yaw=%s game_diffs=%s%s' % ('ok  ' if result['ok'] else 'FAIL', name, label, result.get('ticks'),
                  result['compare'].get('max_position_m'), result['compare'].get('max_velocity_m_s'), result['compare'].get('max_yaw_rad'),
                  len(result['compare'].get('game_difference_ticks', [])), ('' if runs is None else ' recording=%s' % result['recordings'].get('ok'))
                  + ('' if 'law_difference' not in result else ' lab-law-difference-from=%s' % result['law_difference']['first_position_difference_tick'])), flush=True)
    summary = {'checks': len(results), 'failed': sum(1 for r in results if not r['ok']), 'results': results}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'summary.json').write_text(json.dumps(summary, indent=1, default=str))
    print('r16 tapes: %d plays, %d failed' % (summary['checks'], summary['failed']))
    return 1 if summary['failed'] else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
